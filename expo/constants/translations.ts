export const getTranslation = (language: LanguageCode | undefined | null, key: string): string => {
  // Fallback to German if language is undefined or not found
  if (!language || !TRANSLATIONS[language as LanguageCode]) {
    return (TRANSLATIONS.de as any)[key] || key;
  }
  const result = (TRANSLATIONS[language as LanguageCode] as any)[key] || (TRANSLATIONS.de as any)[key];
  return result || key;
};

export const translateText = (language: LanguageCode | undefined | null, text: string): string => {
  if (!text || typeof text !== 'string') return text || 'N/A';
  if (!language || !TRANSLATIONS[language as LanguageCode]) {
    const result = TRANSLATIONS.de[text as keyof typeof TRANSLATIONS.de] || text;
    return (result && typeof result === 'string' && result.trim()) ? result : text;
  }
  // No cross-language fallback here: for a known language, an unknown term is
  // left as-is (it's already in the source language). Falling back to the
  // German map would leak German words into the English UI.
  const translations = TRANSLATIONS[language as LanguageCode] as any;
  const result = translations[text] || text;
  return (result && typeof result === 'string' && result.trim()) ? result : text;
};

// Like translateText, but tolerant of the casing that recipe APIs use for
// ingredient names ("olive oil", "GARLIC" -> the "Olive Oil" / "Garlic"
// dictionary keys). Unknown terms are left untouched.
export const translateIngredientName = (
  language: LanguageCode | undefined | null,
  name: string,
): string => {
  if (!name || typeof name !== 'string') return name || '';
  const direct = translateText(language, name);
  if (direct !== name) return direct;
  const titled = name.toLowerCase().replace(/\b\p{L}/gu, (c) => c.toUpperCase());
  const hit = translateText(language, titled);
  return hit !== titled ? hit : name;
};

export const translateAmount = (language: LanguageCode, amount: string): string => {
  if (!amount || typeof amount !== 'string') return amount || 'N/A';
  
  // Handle exact matches first
  const exactTranslation = translateText(language, amount);
  if (exactTranslation && exactTranslation !== amount) {
    return exactTranslation;
  }
  
  // Split the amount into parts and translate each word
  const words = amount.split(' ').filter(word => word.trim());
  const translatedWords = words.map(word => {
    // Try to translate each word
    const translated = translateText(language, word);
    return (translated && translated !== word) ? translated : word;
  });
  
  return translatedWords.join(' ') || amount;
};